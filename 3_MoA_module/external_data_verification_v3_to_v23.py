import pandas as pd
import numpy as np
import joblib
import json
import tensorflow as tf
tf.keras.utils.disable_interactive_logging()
from tensorflow.keras.models import load_model
import argparse
import os
os.environ['TF_CPP_MIN_LOG_LEVEL'] = '2'


def parse_arguments():
    """Parse command-line arguments and distinguish the two input types"""
    parser = argparse.ArgumentParser(description='Protein-ligand interaction prediction - supports two input modes',
                                     formatter_class=argparse.RawTextHelpFormatter)
    
    # Common required arguments (needed by both modes)
    parser.add_argument('-p', '--protein_file', required=True, 
                        help='Path to protein feature file (contains protein + protein_* columns)')
    parser.add_argument('-l', '--ligand_file', required=True, 
                        help='Path to ligand feature file (contains ligand + ligand_* columns)')
    
    # Mode 1 arguments (specify combination file)
    parser.add_argument('-g', '--combination_file', 
                        help='Mode 1 - path to combination file (contains protein and ligand columns specifying pairs to predict)')
    
    # Mode 2 arguments (specify protein/ligand names, generate all combinations)
    parser.add_argument('-pn', '--protein_names', 
                        help='Mode 2 - list of protein names to predict, comma-separated (e.g. "proteinA,proteinB")')
    parser.add_argument('-ln', '--ligand_names', 
                        help='Mode 2 - list of ligand names to predict, comma-separated (e.g. "ligandX,ligandY")')
    
    # Optional arguments
    parser.add_argument('-t', '--threshold', type=float, 
                        help='Prediction decision threshold (optional; prefers optimal_threshold.json generated during training, then this argument, then default 0.5)')
    parser.add_argument('-o', '--output', default='model_predictions.csv',
                        help='Output file path (default: model_predictions.csv)')
    
    args = parser.parse_args()
    
    # Argument validation: ensure only one mode is selected
    mode1_used = args.combination_file is not None
    mode2_used = (args.protein_names is not None) or (args.ligand_names is not None)
    
    if mode1_used and mode2_used:
        parser.error("Error: cannot specify both mode 1 (-g/--combination_file) and mode 2 (-pn/--ln) arguments")
    if not mode1_used and not mode2_used:
        parser.error("Error: you must choose one input mode\n"
                     "  Mode 1: specify a combination file -g/--combination_file\n"
                     "  Mode 2: specify protein/ligand names -pn/--protein_names and -ln/--ligand_names")
    
    # Mode 2 argument validation
    if mode2_used:
        if args.protein_names is None or args.ligand_names is None:
            parser.error("Error: mode 2 requires both -pn/--protein_names and -ln/--ligand_names")
    
    return args

def load_model_and_preprocessor():
    """Load the trained model, preprocessor, and threshold"""
    print("=== Loading model and preprocessing files ===")
    # Load model
    if not os.path.exists('my_model.h5'):
        raise FileNotFoundError("Model file my_model.h5 not found; make sure the training script ran successfully")
    model = load_model('my_model.h5')
    
    # Load preprocessor
    if not os.path.exists('preprocessor.joblib'):
        raise FileNotFoundError("Preprocessor file preprocessor.joblib not found; make sure the training script ran successfully")
    preprocessor = joblib.load('preprocessor.joblib')
    
    # Load feature columns
    if not os.path.exists('feature_columns.json'):
        raise FileNotFoundError("Feature column file feature_columns.json not found; make sure the training script ran successfully")
    with open('feature_columns.json', 'r') as f:
        required_feature_columns = json.load(f)
    
    # Load threshold
    prediction_threshold = 0.5
    # Priority: command-line value > threshold file generated by training > default 0.5
    if os.path.exists('optimal_threshold.json'):
        with open('optimal_threshold.json', 'r') as f:
            threshold_data = json.load(f)
        prediction_threshold = threshold_data['optimal_threshold']
        print(f"Loaded optimal threshold from file: {prediction_threshold:.4f}")
    
    if args.threshold is not None:
        prediction_threshold = args.threshold
        print(f"Using threshold specified on the command line: {prediction_threshold:.4f}")
    
    print(f"Final prediction threshold: {prediction_threshold:.4f}")
    
    # Label mapping (fixed rule)
    label_map = {1: 'ACTIVATING', 0: 'INHIBITORY'}
    
    return model, preprocessor, required_feature_columns, prediction_threshold, label_map

def load_combination_data(args):
    """Load/generate combination data according to the selected mode"""
    print("\n=== Loading input data ===")
    # Load protein and ligand feature files
    protein_df = pd.read_csv(args.protein_file)
    ligand_df = pd.read_csv(args.ligand_file)
    
    # Verify that the feature files contain the required columns
    if 'protein' not in protein_df.columns:
        raise ValueError(f"Protein feature file {args.protein_file} is missing the 'protein' column")
    if 'ligand' not in ligand_df.columns:
        raise ValueError(f"Ligand feature file {args.ligand_file} is missing the 'ligand' column")
    
    # Mode 1: use the specified combination file
    if args.combination_file:
        print(f"Mode 1 - loading combination file: {args.combination_file}")
        combo_df = pd.read_csv(args.combination_file)
        
        # Validate combination file columns
        if 'protein' not in combo_df.columns or 'ligand' not in combo_df.columns:
            raise ValueError(f"Combination file {args.combination_file} must contain 'protein' and 'ligand' columns")
        
        # Filter combinations: keep only entries present in the protein and ligand feature files
        valid_proteins = set(protein_df['protein'].unique())
        valid_ligands = set(ligand_df['ligand'].unique())
        
        combo_df = combo_df[
            combo_df['protein'].isin(valid_proteins) & 
            combo_df['ligand'].isin(valid_ligands)
        ]
        
        if len(combo_df) == 0:
            raise ValueError("No valid combinations found in the combination file that exist in the protein/ligand feature files")
        
        print(f"Combination file loaded, valid combinations: {len(combo_df)}")
    
    # Mode 2: generate all combinations of the specified proteins/ligands
    else:
        print(f"Mode 2 - generating all combinations of the specified proteins/ligands")
        # Parse the protein and ligand name lists
        protein_names = [p.strip() for p in args.protein_names.split(',')]
        ligand_names = [l.strip() for l in args.ligand_names.split(',')]
        
        # Filter data in the feature files
        protein_filtered = protein_df[protein_df['protein'].isin(protein_names)]
        ligand_filtered = ligand_df[ligand_df['ligand'].isin(ligand_names)]
        
        # Verify that the specified proteins/ligands exist
        missing_proteins = set(protein_names) - set(protein_filtered['protein'].unique())
        missing_ligands = set(ligand_names) - set(ligand_filtered['ligand'].unique())
        
        if missing_proteins:
            print(f"Warning: the following proteins were not found in the feature file: {', '.join(missing_proteins)}")
        if missing_ligands:
            print(f"Warning: the following ligands were not found in the feature file: {', '.join(missing_ligands)}")
        
        if len(protein_filtered) == 0 or len(ligand_filtered) == 0:
            raise ValueError("No valid protein/ligand data found; cannot generate combinations")
        
        # Generate the Cartesian product (all combinations)
        protein_filtered['_tmp_key'] = 1
        ligand_filtered['_tmp_key'] = 1
        combo_df = pd.merge(protein_filtered, ligand_filtered, on='_tmp_key').drop('_tmp_key', axis=1)
        combo_df = combo_df[['protein', 'ligand']].drop_duplicates()
        
        print(f"All combinations generated, count: {len(combo_df)}")
        print(f"Proteins involved: {len(protein_filtered)} | Ligands involved: {len(ligand_filtered)}")
    
    # Merge feature data
    full_df = pd.merge(combo_df, protein_df, on='protein', how='left')
    full_df = pd.merge(full_df, ligand_df, on='ligand', how='left')
    
    return full_df

def predict_and_save(args, full_df, model, preprocessor, required_cols, threshold, label_map):
    """Run prediction and save results"""
    print("\n=== Running prediction ===")
    # Validate feature columns
    missing_cols = set(required_cols) - set(full_df.columns)
    if missing_cols:
        raise ValueError(f"Missing feature columns required by the model: {', '.join(missing_cols)}")
    
    # Prepare input features
    X_new = full_df[required_cols].copy()
    
    # Apply preprocessing
    X_new_processed = preprocessor.transform(X_new)
    
    # Model prediction
    y_pred_proba = model.predict(X_new_processed, batch_size=32, verbose=1).ravel()
    
    # Convert to class labels
    y_pred_class = (y_pred_proba >= threshold).astype(int)
    y_pred_label = pd.Series(y_pred_class).map(label_map).values
    
    # Assemble results
    result_df = full_df[['protein', 'ligand']].copy()
    result_df['Predicted_Probability'] = y_pred_proba
    result_df['Predicted_Priority'] = y_pred_label
    result_df['Predicted_Class'] = y_pred_class
    
    # Save results
    result_df.to_csv(args.output, index=False)
    print(f"\n=== Prediction complete ===")
    print(f"Results saved to: {args.output}")
    print(f"\nPrediction summary:")
    print(f"  Total predictions: {len(result_df)}")
    print(f"  ACTIVATING: {(result_df['Predicted_Priority'] == 'ACTIVATING').sum()}")
    print(f"  INHIBITORY: {(result_df['Predicted_Priority'] == 'INHIBITORY').sum()}")
    print(f"  Mean predicted probability: {result_df['Predicted_Probability'].mean():.4f}")

if __name__ == "__main__":
    # 1. Parse arguments
    args = parse_arguments()
    
    try:
        # 2. Load model and preprocessing files
        model, preprocessor, required_cols, threshold, label_map = load_model_and_preprocessor()
        
        # 3. Load/generate combination data
        full_df = load_combination_data(args)
        
        # 4. Run prediction and save results
        predict_and_save(args, full_df, model, preprocessor, required_cols, threshold, label_map)
        
    except Exception as e:
        print(f"\nError: {str(e)}")
        exit(1)